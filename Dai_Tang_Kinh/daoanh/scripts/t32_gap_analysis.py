# Build regex: era_name + optional_regnal_year + 年
# Regnal year can be: 一二三四五六七八九十百 + 年, or 中/間
ERA_YEAR_PAT_TEMPLATE = r'(%s)([一二三四五六七八九十百千]+年|中|間)'

# Get all missing 寺 places with notes
missing = conn.execute("""
    SELECT pd.id, pd.name_zh, pd.note
    FROM places_dila pd
    WHERE pd.note_category LIKE '%寺%'
    AND pd.note IS NOT NULL AND length(pd.note) > 20
    AND NOT EXISTS (SELECT 1 FROM place_timeline_events pt WHERE pt.dila_id = pd.id)
""").fetchall()

print(f'Total missing 寺 places with notes: {len(missing)}')

# Chinese numeral to int
def cn_to_int(cn):
    """Convert Chinese year number like 十五 → 15, 三十八 → 38"""
    cn = cn.replace('年', '')
    if not cn:
        return 1
    if cn == '中':
        return None  # midpoint, not specific year
    if cn == '間':
        return None
    
    result = 0
    current = 0
    for ch in cn:
        if ch == '十':
            if current == 0:
                current = 1
            result += current
            current = 0
            if result == 0:
                result = 1
        elif ch == '百':
            if current == 0:
                current = 1
            result += current * 100
            current = 0
        elif ch == '千':
            if current == 0:
                current = 1
            result += current * 1000
            current = 0
        elif ch == '二':
            current = 2
        elif ch == '三':
            current = 3
        elif ch == '四':
            current = 4
        elif ch == '五':
            current = 5
        elif ch == '六':
            current = 6
        elif ch == '七':
            current = 7
        elif ch == '八':
            current = 8
        elif ch == '九':
            current = 9
        elif ch == '一':
            current = 1
    result += current
    return result if result > 0 else None

# Count how many missing notes match era names
era_matched = 0
era_samples = []
era_ce_matched = 0  # notes that have parenthesized CE year (already extracted)
era_only_matched = 0  # notes that ONLY have era name (NOT yet extracted)

for (pid, name, note) in missing:
    if not note:
        continue
    # Check if has parenthesized CE year
    has_ce = bool(re.search(r'（\d{3,4}）', note))
    
    # Check era name match
    found_era = False
    for era in era_names:
        if era in note:
            found_era = True
            break
    
    if found_era:
        era_matched += 1
        if has_ce:
            era_ce_matched += 1
        else:
            era_only_matched += 1
            if len(era_samples) < 20:
                # Find which era and compute year
                for era in era_names:
                    if era in note:
                        idx = note.index(era)
                        after = note[idx+len(era):idx+len(era)+10]
                        m = re.match(r'([一二三四五六七八九十百千]+年|中|間)', after)
                        if m:
                            yr_str = m.group(1)
                            yr_num = cn_to_int(yr_str)
                            era_info = ERA_TABLE[era]
                            if yr_num:
                                ce_year = era_info[0] + yr_num - 1
                            else:
                                ce_year = (era_info[0] + era_info[1]) // 2
                            era_samples.append((pid, name, era, yr_str, ce_year, note[:150]))
                            break

